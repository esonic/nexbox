/*
 * inject.so — injects CLAUDE_CODE_OAUTH_TOKEN into the Claude CLI process
 * via LD_PRELOAD so the token never appears in process args or plain env.
 *
 * The token is XOR-obfuscated (key = XOR_KEY) to prevent extraction via
 * `strings`. This is not cryptographic — goal is to avoid the token showing
 * up as a plain string in the binary.
 *
 * Usage:
 *   LD_PRELOAD=/usr/lib/inject.so claude ...
 *
 * To update the token:
 *   sudo inject/rotate.sh <new_token>
 *
 * rotate.sh XOR-encodes the token, compiles a temp copy of this file,
 * installs the result to /opt/boxnex/inject.so, and cleans up — this
 * file is never modified and the token never touches disk as plaintext.
 */

#include <stdlib.h>
#include <string.h>

#define XOR_KEY 0x5A

/* Generated by encode.sh — replace this array when rotating the token */
static const unsigned char enc_token[] = {
    /* PLACEHOLDER: run encode.sh <token> and paste the output here */
    0x39, 0x31, 0x3e,
};

__attribute__((constructor)) static void inject_token(void) {
    size_t len = sizeof(enc_token);
    char *token = malloc(len + 1);
    if (!token) return;
    for (size_t i = 0; i < len; i++) {
        token[i] = (char)(enc_token[i] ^ XOR_KEY);
    }
    token[len] = '\0';
    setenv("CLAUDE_CODE_OAUTH_TOKEN", token, 1);
    memset(token, 0, len + 1);
    free(token);
}
